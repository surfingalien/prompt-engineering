// ─── Eval assertions ─────────────────────────────────────────────────────────
// Deterministic checks run in the browser; `rubric` checks are graded by a
// model via /api/grade. Pure (except rubric), unit tested in Node.

export const ASSERTION_TYPES = [
  { id: 'contains', label: 'Contains', hint: 'Text that must appear (case-insensitive)' },
  { id: 'not_contains', label: 'Does not contain', hint: 'Text that must not appear' },
  { id: 'regex', label: 'Matches regex', hint: 'JavaScript regular expression, e.g. ^\\d{3}' },
  { id: 'max_words', label: 'At most N words', hint: 'A number' },
  { id: 'min_words', label: 'At least N words', hint: 'A number' },
  { id: 'is_json', label: 'Is valid JSON', hint: 'No value needed — fenced ```json blocks are accepted' },
  { id: 'json_has', label: 'JSON has keys', hint: 'Comma-separated keys, e.g. name,score' },
  { id: 'rubric', label: 'Graded by Claude', hint: 'Plain-language rubric, e.g. “Cites the source and stays neutral”' },
];

const wordCount = s => (String(s).trim().match(/\S+/g) || []).length;

function extractJson(text) {
  const t = String(text).trim();
  const fenced = /```(?:json)?\s*([\s\S]*?)```/i.exec(t);
  const candidate = fenced ? fenced[1] : t;
  return JSON.parse(candidate);
}

/** @returns {{pass:boolean, reason:string} | null} null for model-graded types */
export function checkAssertion(a, output) {
  const out = String(output ?? '');
  const v = String(a.value ?? '');
  switch (a.type) {
    case 'contains': return { pass: out.toLowerCase().includes(v.toLowerCase()), reason: `expected to contain “${v}”` };
    case 'not_contains': return { pass: !out.toLowerCase().includes(v.toLowerCase()), reason: `expected not to contain “${v}”` };
    case 'regex': {
      try { return { pass: new RegExp(v, 'm').test(out), reason: `expected to match /${v}/` }; }
      catch (e) { return { pass: false, reason: `invalid regex: ${e.message}` }; }
    }
    case 'max_words': { const n = wordCount(out); return { pass: n <= Number(v), reason: `${n} words (max ${v})` }; }
    case 'min_words': { const n = wordCount(out); return { pass: n >= Number(v), reason: `${n} words (min ${v})` }; }
    case 'is_json': {
      try { extractJson(out); return { pass: true, reason: 'valid JSON' }; }
      catch (e) { return { pass: false, reason: `invalid JSON: ${e.message}` }; }
    }
    case 'json_has': {
      try {
        const obj = extractJson(out);
        const keys = v.split(',').map(k => k.trim()).filter(Boolean);
        const missing = keys.filter(k => !(obj && typeof obj === 'object' && k in obj));
        return { pass: !missing.length, reason: missing.length ? `missing keys: ${missing.join(', ')}` : 'all keys present' };
      } catch (e) { return { pass: false, reason: `invalid JSON: ${e.message}` }; }
    }
    case 'rubric': return null;
    default: return { pass: false, reason: `unknown assertion type ${a.type}` };
  }
}

/** Export a suite as a promptfoo config so it can run in CI. */
export function toPromptfooYaml({ name, system, user, model, cases }) {
  const q = s => JSON.stringify(String(s ?? ''));
  const indent = (s, n) => String(s).split('\n').map(l => ' '.repeat(n) + l).join('\n');
  const msgs = [];
  if (system) msgs.push({ role: 'system', content: system });
  msgs.push({ role: 'user', content: user });
  const typeMap = { contains: 'icontains', not_contains: 'not-icontains', regex: 'regex', is_json: 'is-json', rubric: 'llm-rubric' };
  const out = [
    `# Generated by PromptForge — run with: npx promptfoo eval`,
    `description: ${q(name || 'PromptForge eval')}`,
    'prompts:',
    `  - ${q(JSON.stringify(msgs))}`,
    'providers:',
    `  - id: anthropic:messages:${model || 'claude-opus-5-5'}`,
    '    config:',
    '      max_tokens: 4096',
    'tests:',
  ];
  for (const c of cases || []) {
    out.push(`  - description: ${q(c.name || 'case')}`);
    const vars = Object.entries(c.vars || {});
    if (vars.length) { out.push('    vars:'); for (const [k, v] of vars) out.push(`      ${k}: ${q(v)}`); }
    out.push('    assert:');
    for (const a of c.assertions || []) {
      if (typeMap[a.type]) {
        out.push(`      - type: ${typeMap[a.type]}`);
        if (a.type !== 'is_json') out.push(`        value: ${q(a.value)}`);
      } else if (a.type === 'max_words' || a.type === 'min_words') {
        const op = a.type === 'max_words' ? '<=' : '>=';
        out.push('      - type: javascript', `        value: ${q(`output.trim().split(/\\s+/).length ${op} ${Number(a.value) || 0}`)}`);
      } else if (a.type === 'json_has') {
        const keys = String(a.value).split(',').map(k => k.trim()).filter(Boolean);
        out.push('      - type: javascript', `        value: ${q(`(() => { const o = JSON.parse(output); return ${JSON.stringify(keys)}.every(k => k in o); })()`)}`);
      }
    }
    if (!(c.assertions || []).length) out.push(indent('- type: javascript\n  value: "true"', 6));
  }
  return out.join('\n') + '\n';
}
